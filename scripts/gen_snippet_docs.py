def build(lang):
    t = T[lang]
    lib = L.load_library()
    if lib.errors:
        raise SystemExit("library has errors:\n" + "\n".join(lib.errors))
    li = L.LANGS.index(lang)
    by_cat = {c: [s for s in sorted(lib.snippets) if lib.snippets[s]["category"] == c] for c in L.CATEGORIES}
    out = [f"# {t['title']}", "", t["other"], "", t["intro"].format(n=len(lib.snippets), c=len(L.CATEGORIES)), "",
           f"> {t['generated']}", "", f"## {t['safety']}", "", *t["safety_body"], "", f"## {t['priv']}", "",
           t["priv_head"], "|---|---|"]
    out += [f"| `{k}` | {v[li]} |" for k, v in L.PRIVILEGES.items()]
    out += ["", f"## {t['types']}", "", *t["types_body"], "", f"## {t['use']}", "", *t["use_body"], "",
            f"## {t['mcp']}", "", *t["mcp_body"], "", f"## {t['cats']}", "", t["cat_head"], "|---|---|---|"]
    out += [f"| [{c}](#{c}) | {L.CATEGORIES[c][li]} | {len(ids)} |" for c, ids in by_cat.items()]
    for c, ids in by_cat.items():
        out += ["", f"## {c}", "", f"**{L.CATEGORIES[c][li]}** — {t['source']}: "
                f"[`plugins/ssh-connector/snippets/{c}.yaml`](../plugins/ssh-connector/snippets/{c}.yaml)", "",
                t["list_head"], "|---|---|---|---|"]
        for sid in ids:
            s = lib.snippets[sid]
            params = ", ".join(f"`{p['name']}`" for p in s["params"]) or "—"
            out.append(f"| `{sid}` | {s['name'][lang]} | `{s['privilege']}` | {params} |")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv
    stale = []
    for lang, path in OUT.items():
        text = build(lang)
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print("out of date: " + ", ".join(stale) + " (run scripts/gen_snippet_docs.py)")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
